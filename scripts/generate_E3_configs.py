"""
generate_E3_configs.py — emit one config per E2 outer-LOCO fold for E3.

Each config is minimal — just `outer_anion` and the PySR knobs that match
what Harness uses internally (populations=40, population_size=33,
niterations=100, maxsize=25, parsimony=0.05, binary/unary operators).

n_seeds is 5 per fold, n_rounds is 10 per seed → 50 PySR fits per fold
→ 500 PySR fits across the 10 folds. At ~5-10 seconds per fit on
N≈170 training samples, total wall-clock is ~40-80 minutes.

Run once; outputs go to experiments/E3_matched_pysr_baselines/configs/.
"""

from __future__ import annotations

from pathlib import Path
import yaml


OUT_DIR = Path("experiments/E3_matched_pysr_baselines/configs")
ANIONS = ("O", "S", "Se", "Te", "F", "Cl", "Br", "I", "N", "P")

FOLD_HEADER_FMT = (
    "# E3 fold config — outer_anion={anion}\n"
    "# Autogenerated by scripts/generate_E3_configs.py.\n"
    "# Do not hand-edit; re-run the generator instead.\n"
)

# PySR config matched to what Harness uses per round (see E1_default.yaml).
PYSR_CFG = {
    "populations":     40,
    "population_size": 33,
    "niterations":     100,
    "binary_operators": ["+", "-", "*", "/"],
    # Give vanilla PySR the SAME operator alphabet Harness ends up with
    # after the adaptive scheduler adds cbrt/cube. Otherwise the two
    # searches have different algebraic reach and the comparison is
    # about operators, not about governance.
    "unary_operators": ["exp", "log", "sqrt", "square", "inv", "cube", "cbrt"],
    "maxsize":         25,
    "parsimony":       0.05,
}


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for anion in ANIONS:
        cfg = {
            "project": {
                "name": "HARNESS-2D-RI",
                "version": f"2.0.0-E3-{anion}",
                "description": (
                    f"E3 matched-PySR baseline, outer_anion={anion}. "
                    "Same outer split as E2; no council, no memory, "
                    "no causal diagnostics, no adaptive operators."
                ),
            },
            "target":    "cauchy_A",
            "data_csv":  "data/extended/tier2_binary.csv",
            "outer_anion": anion,
            "n_seeds":   5,
            "n_rounds":  10,
            "stability_range": [0.0, 20.0],
            "pysr":      PYSR_CFG,
        }
        path = OUT_DIR / f"fold_{anion}.yaml"
        payload = FOLD_HEADER_FMT.format(anion=anion) + yaml.safe_dump(
            cfg, default_flow_style=False, sort_keys=False,
        )
        path.write_text(payload)
        print(f"  wrote {path}")
    print(f"Generated {len(ANIONS)} E3 configs in {OUT_DIR}")


if __name__ == "__main__":
    main()
