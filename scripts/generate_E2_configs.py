"""
generate_E2_configs.py — emit the ten per-fold configs for E2_outer_loco.

Each fold config is a near-copy of E1's config with:
  - `outer_anion` set to the held-out anion
  - `output.save_dir` redirected to the fold's run dir
  - a short fold-specific note

Run once; outputs go to experiments/E2_outer_loco/configs/.
Every generated file begins with a warning not to hand-edit — version
changes should go through this script, then git-commit both the script
change and the regenerated yaml files together.
"""

from __future__ import annotations

from pathlib import Path
import yaml


BASE_CFG_PATH = Path("experiments/E1_full_harness_fixed_council/configs/E1_default.yaml")
OUT_DIR = Path("experiments/E2_outer_loco/configs")
ANIONS = ("O", "S", "Se", "Te", "F", "Cl", "Br", "I", "N", "P")

FOLD_HEADER_FMT = (
    "# E2 fold config — outer_anion={anion}\n"
    "# Autogenerated by scripts/generate_E2_configs.py.\n"
    "# Do not hand-edit; re-run the generator instead.\n"
)


def main() -> None:
    base = yaml.safe_load(BASE_CFG_PATH.read_text())
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    for anion in ANIONS:
        cfg = dict(base)  # shallow copy is fine — we only mutate top keys
        cfg["outer_anion"] = anion
        cfg["project"] = {
            **base["project"],
            "version": f"2.0.0-E2-{anion}",
            "description": (
                f"E2 outer-LOCO fold: held-out anion = {anion}. "
                "Harness searches on the other 9 anions; headline is "
                "evaluated on the held-out anion as the leakage-free metric."
            ),
        }
        cfg["output"] = {
            **base.get("output", {}),
            "save_dir": f"experiments/E2_outer_loco/runs/fold_{anion}/",
        }
        # Stability range for outer-test evaluation (paper §3.1 range [1, 20]
        # matches the ValidatorAgent's physical-range gate).
        cfg["stability_range"] = [0.0, 20.0]

        path = OUT_DIR / f"fold_{anion}.yaml"
        payload = FOLD_HEADER_FMT.format(anion=anion) + yaml.safe_dump(
            cfg, default_flow_style=False, sort_keys=False,
        )
        path.write_text(payload)
        print(f"  wrote {path}")

    print(f"Generated {len(ANIONS)} fold configs in {OUT_DIR}")


if __name__ == "__main__":
    main()
